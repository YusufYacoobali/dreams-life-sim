"""Import original generated icon sprites, preserving authored RGBA and aspect.

Alpha components locate illustrations and assign detached highlights to their
nearest illustration. This is sprite registration, not colour segmentation or
replacement artwork. Requires Pillow, NumPy and SciPy.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'assets/generated/polish'
OUT.mkdir(parents=True,exist_ok=True)
SHEETS = {
    'event-icons.png': ['toys','mischief','school-life','friends','family-life','surprise','everyday','health-check','life-star','archive','settings','loan'],
    'pet-icons.png': ['pet-cat','pet-dog','pet-rabbit','pet-bird','pet-feed','pet-vet','pet-play','pet-training','pet-memorial','pet-walk','pet-bed','pet-adoption'],
}
manifest = {'generator':'built-in image_gen.imagegen only','reference':'assets/generated/activity-atlas.png','sources':[],'icons':{}}
for file,keys in SHEETS.items():
    source = ROOT/'design/polish'/file
    pixels = np.array(Image.open(source).convert('RGBA'))
    labels,_ = ndi.label(pixels[:,:,3]>32)
    counts = np.bincount(labels.ravel());counts[0]=0
    main = np.argsort(counts)[-len(keys):]
    assert min(counts[main])>10000, (file,'missing illustration')
    bounds = ndi.find_objects(labels)
    centres = {int(label):ndi.center_of_mass(np.ones_like(labels),labels,int(label)) for label in main}
    ordered = sorted(main,key=lambda label:centres[int(label)][0])
    ordered = [label for row in range(0,len(keys),4) for label in sorted(ordered[row:row+4],key=lambda label:centres[int(label)][1])]
    # Include detached sparkles, steam and antialiased edges with their parent.
    owners = np.zeros(len(counts),dtype=np.int32)
    for label in range(1,len(counts)):
        if counts[label]:
            centre = ndi.center_of_mass(np.ones_like(labels),labels,label)
            owners[label] = min(main,key=lambda parent:sum((a-b)**2 for a,b in zip(centre,centres[int(parent)])))
    nearest = ndi.distance_transform_edt(labels==0,return_distances=False,return_indices=True)
    ownership = owners[labels[tuple(nearest)]]
    rects = []
    for key,label in zip(keys,ordered):
        keep = (ownership==label)&(pixels[:,:,3]>0)
        yy,xx = np.where(keep)
        rect = [max(0,int(xx.min())-2),max(0,int(yy.min())-2),min(pixels.shape[1],int(xx.max())+3),min(pixels.shape[0],int(yy.max())+3)]
        x0,y0,x1,y1 = rect
        sprite = pixels[y0:y1,x0:x1].copy()
        sprite[~keep[y0:y1,x0:x1]] = 0
        image = Image.fromarray(sprite)
        image.thumbnail((244,244),Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA',(256,256))
        canvas.paste(image,((256-image.width)//2,(256-image.height)//2))
        clean = np.array(canvas);clean[clean[:,:,3]==0,:3]=0
        target = OUT/(key+'.png');Image.fromarray(clean).save(target,optimize=True)
        manifest['icons'][key] = {'file':target.name,'size':[256,256],'bytes':target.stat().st_size,'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}
        rects.append({'id':key,'rect':rect})
    manifest['sources'].append({'file':'design/polish/'+file,'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'sprites':rects})
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
registry = '// Generated by tools/build-polish-art.py. Bundled offline artwork.\nexport const polishImages = {\n'
for key in manifest['icons']:
    registry += f"  '{key}': require('../../assets/generated/polish/{key}.png'),\n"
registry += '} as const;\nexport type PolishArtId = keyof typeof polishImages;\n'
(ROOT/'src/assets/polishImages.ts').write_text(registry)
print(json.dumps({'icons':len(manifest['icons']),'bytes':sum(icon['bytes'] for icon in manifest['icons'].values())}))
