"""Measure each head/age/contour, independently of skin colour and hair choice.

These tiny fitting records reuse the illustrated wigs; no extra portraits or
runtime pixel scanning. Coordinates are in the original 320px artwork space.
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'assets/generated/avatars-v2'
manifest = json.loads((OUT/'manifest.json').read_text())
heads = []
for identity in range(16):
    stages = []
    for stage in range(8):
        skin = manifest['defaults']['skin'][identity]
        atlas = np.array(Image.open(OUT/f'head-{identity}-{stage}-{skin}.png'))
        faces = []
        for face in range(4):
            alpha = atlas[:,face*272:(face+1)*272,3] > 220
            crown = int(np.where(alpha)[0].min()) + 44
            def bounds(y):
                x = np.where(alpha[y-44])[0]
                return float(x.min()+24), float(x.max()+24+1)
            left,right = bounds(crown+86)
            cheek_left,cheek_right = bounds(crown+166)
            width = .8*(right-left)+.2*(cheek_right-cheek_left)
            # Long hair occludes ears outside the temples. The same face pixels
            # remain at their original positions inside this narrower crop.
            faces.append([round((left+right)/2,2),round(width,2),crown,left+3,right-3])
        stages.append(faces)
    heads.append(stages)
target = ROOT/'src/assets/portraitFit.ts'
necklines = []
for outfit in range(16):
    alpha = np.array(Image.open(OUT/f'clothing-{outfit}.png'))[:,:,3]
    opening = {}
    for y in range(180,320):
        if alpha[y,160] < 128:
            a = np.where(alpha[y,:160] > 128)[0]
            b = np.where(alpha[y,160:] > 128)[0]+160
            if len(a) and len(b):
                opening[y] = (int(a.max()),int(b.min()))
    first_y = min(opening)
    ages = []
    for neck_width in [104,68,64,60]:
        left,right = [],[]
        for y in range(180,321):
            lo,hi = 160-neck_width//2,160+neck_width//2
            if y < first_y:
                # A short neck flares continuously into the opening rather
                # than ending in a wide horizontal strip below a child's jaw.
                t = np.clip((y-200)/max(1,first_y-200),0,1)
                t = t*t*(3-2*t)
                lo = round(lo*(1-t)+opening[first_y][0]*t,2)
                hi = round(hi*(1-t)+opening[first_y][1]*t,2)
            elif y in opening:
                lo,hi = opening[y]
            left.append((lo,y));right.append((hi,y))
        points = left+right[::-1]
        ages.append('M'+' L'.join(f'{x},{y}' for x,y in points)+' Z')
    necklines.append(ages)
target.write_text('// Generated by tools/build-avatar-v2-fit.py from actual head alpha silhouettes.\n'
                  '// Per identity, age stage, saved contour: centre, width, crown, hair-covered ear clip bounds.\n'
                  'export const naturalFaces = '+json.dumps(manifest['defaults']['face'])+' as const;\n'
                  'export const headFits: readonly (readonly (readonly (readonly number[])[])[])[] = '
                  +json.dumps(heads,separators=(',',':'))+';\n'
                  +'// Skin is visible only inside the actual garment opening.\n'
                  +'export const necklinePaths = '+json.dumps(necklines,separators=(',',':'))+' as const;\n')
print(json.dumps({'measuredHeadFits':16*8*4}))
