"""Measure unmodified image_gen atlas subjects for native catalogue clipping.

This only reads artwork and emits coordinates/provenance; it never edits PNGs.
Requires Pillow, numpy and scipy. Run from the repository root.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'homes': ('catalogue-homes.png', 4, [
        'studio', 'apartment', 'terrace', 'family-house',
        'country-home', 'penthouse', 'mobile-home', 'woodland-cabin',
        'village-flat', 'garden-flat', 'brick-bungalow', 'duplex',
        'warehouse-loft', 'canal-townhouse', 'lake-house', 'mountain-chalet',
        'victorian-villa', 'beach-house', 'modern-villa', 'country-estate',
    ]),
    'vehicles': ('catalogue-vehicles.png', 5, [
        'used-compact', 'city-car', 'family-car', 'electric-car', 'sports-car',
        'motorbike', 'used-scooter', 'city-scooter', 'used-saloon', 'compact-suv',
        'family-minivan', 'pickup', 'delivery-van', 'vintage-roadster', 'convertible',
        'executive-saloon', 'luxury-suv', 'campervan', 'supercar', 'grand-tourer',
    ]),
}
atlases, records = {}, {}
for atlas, (file, columns, names) in SOURCES.items():
    path = ROOT/'assets/generated'/file
    image = Image.open(path).convert('RGBA')
    pixels = np.asarray(image)
    labels, _ = ndi.label(pixels[:, :, 3] > 32)
    areas = np.bincount(labels.ravel()); areas[0] = 0
    components = np.flatnonzero(areas > 2000)
    assert len(components) == len(names), (file, len(components))
    objects = ndi.find_objects(labels)
    parts = []
    for component in components:
        ys, xs = objects[component-1]
        parts.append((ys.start, xs.start, component, xs.stop, ys.stop))
    parts.sort()
    ordered = []
    for row in range(0, len(parts), columns):
        ordered.extend(sorted(parts[row:row+columns], key=lambda part: part[1]))
    for name, (top, left, component, right, bottom) in zip(names, ordered):
        x, y = max(0,left-2), max(0,top-2)
        right, bottom = min(image.width,right+2), min(image.height,bottom+2)
        region = labels[y:bottom,x:right]
        assert not any(areas[int(other)] > 2000 for other in np.unique(region) if other not in (0,component)), name
        alpha = pixels[y:bottom,x:right,3]
        edge = np.concatenate((alpha[0],alpha[-1],alpha[:,0],alpha[:,-1]))
        assert int(edge.max()) <= 32, (name,'opaque crop edge')
        records[name] = {'atlas':atlas,'rect':[x,y,right-x,bottom-y]}
    atlases[atlas] = {'file':file,'size':list(image.size),'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'subjects':len(names)}

text = '// Generated by tools/register-catalogue-art.py; unmodified source PNGs.\n'
text += 'export type CatalogueAtlas = \'homes\' | \'vehicles\';\n'
text += 'export const catalogueAtlasSizes: Record<CatalogueAtlas, readonly [number, number]> = '+json.dumps({key:item['size'] for key,item in atlases.items()})+';\n'
text += 'export const catalogueArt: Record<string, { atlas: CatalogueAtlas; rect: readonly [number, number, number, number] }> = {\n'
for name, record in records.items():
    text += '  '+json.dumps(name)+': { atlas:'+json.dumps(record['atlas'])+', rect:'+json.dumps(record['rect'])+' },\n'
text += '};\n'
(ROOT/'src/assets/catalogueLayout.ts').write_text(text)
manifest = {'generator':'built-in image_gen.imagegen only','reference':'design/07-assets-finances-investing-properties-vehicles.png',
            'style':'Original colourful softly dimensional illustrations, matching the established ownership artwork.',
            'pngsUnmodified':True,'runtimeNetworkRequired':False,'atlases':atlases,'illustrations':records,
            'sourceOriginals':{'homes':'/workspace/generated_images/exec-5d133248-e3c6-4828-bdbd-f5b8e4f47347.png','vehicles':'/workspace/generated_images/exec-3e3706af-cbd7-40d3-9714-d7f4fcff6e79.png'},
            'checks':{'independentSubjects':len(records),'noOpaqueCropEdges':True,'noNeighbouringSubjectInCrop':True}}
(ROOT/'assets/generated/catalogue-art.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps({'atlases':len(atlases),'independentSubjects':len(records),'pngBytes':sum((ROOT/'assets/generated'/item['file']).stat().st_size for item in atlases.values())}))
