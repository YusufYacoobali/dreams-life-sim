import React from 'react';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react-native';
import { SafeAreaProvider } from 'react-native-safe-area-context';
import { createGameStore } from '../../src/state/gameStore';
import { decodeWorld, encodeWorld } from '../../src/game/model';
import { endEmployment } from '../../src/game/systems/work';
import { accountFor } from '../../src/game/systems/common';
import { SaveRepository } from '../../src/persistence/repository';
import { database } from '../support/sqlite';
import { ThemeProvider } from '../../src/ui/theme';
import fixture from '../fixtures/v3-employed-graduate.json';
let mockStore: ReturnType<typeof createGameStore>;
jest.mock('expo-router', () => ({ router: { back: jest.fn(), push: jest.fn() } }));
jest.mock('../../src/state/useGame', () => ({ useGame: (selector: unknown) => require('zustand').useStore(mockStore, selector) }));
import Politics from '../../app/(game)/politics';
import { PendingEvent } from '../../src/ui/PendingEvent';
const frame = (content: React.ReactNode) => <SafeAreaProvider initialMetrics={{ frame: { x: 0, y: 0, width: 390, height: 844 }, insets: { top: 47, bottom: 34, left: 0, right: 0 } }}><ThemeProvider>{content}<PendingEvent /></ThemeProvider></SafeAreaProvider>;
test('native campaign failure rolls back registration and the rival; retry, real election and cold SQLite keep the same candidate and outcome', async () => {
    const { sqlite, driver } = database(), repository = new SaveRepository(driver);
    await repository.initialise();
    const initial = decodeWorld(JSON.stringify(fixture));
    endEmployment(initial);
    const person = initial.people[initial.activePersonId], cash = accountFor(initial);
    person.skills.politics = 80;
    person.stats.health = 100;
    person.stats.smarts = 90;
    person.stats.respect = 80;
    person.publicLife.image = 80;
    cash.cash += 100000000n;
    cash.openingCash += 100000000n;
    initial.random.outcomes = 1;
    await repository.create(initial);
    mockStore = createGameStore({ repository: async () => repository, date: () => initial.date, id: () => 'life_unused' });
    await mockStore.getState().bootstrap();
    const view = render(frame(<Politics />));
    expect(encodeWorld(mockStore.getState().world!)).toBe(encodeWorld(initial));
    fireEvent.press(screen.getByRole('button', { name: 'Review Candidacy' }));
    sqlite.exec("CREATE TRIGGER fail_campaign BEFORE INSERT ON receipts BEGIN SELECT RAISE(ABORT,'storage failure'); END");
    await act(async () => { fireEvent.press(screen.getByRole('button', { name: 'Start Campaign' })); });
    await waitFor(() => expect(screen.getByText(/couldn't be saved/)).toBeOnTheScreen());
    expect(await repository.load(initial.id)).toEqual(initial);
    expect(mockStore.getState().world!.elections).toEqual([]);
    expect(Object.keys(mockStore.getState().world!.people)).toEqual(Object.keys(initial.people));
    sqlite.exec('DROP TRIGGER fail_campaign');
    fireEvent.press(screen.getByRole('button', { name: 'Review Candidacy' }));
    await act(async () => { fireEvent.press(screen.getByRole('button', { name: 'Start Campaign' })); });
    await waitFor(() => expect(screen.getByText('Your campaign has begun')).toBeOnTheScreen());
    const started = mockStore.getState().world!, race = started.elections[0];
    expect(started.elections).toHaveLength(1);
    expect(Object.keys(started.people)).toHaveLength(Object.keys(initial.people).length + 1);
    expect(race.candidates[0].spent).toBe(race.candidates[0].registration);
    expect(started.people[person.id].employment).toBeNull();
    await act(async () => { fireEvent.press(screen.getByRole('button', { name: 'Continue' })); });
    const beforeElection=mockStore.getState().world!;sqlite.exec("CREATE TRIGGER fail_election BEFORE INSERT ON receipts BEGIN SELECT RAISE(ABORT,'storage failure'); END");await act(async()=>{expect(await mockStore.getState().dispatch({type:'advance'})).toBe(false);});expect(await repository.load(initial.id)).toEqual(beforeElection);expect(mockStore.getState().world).toEqual(beforeElection);expect(await repository.snapshots(initial.id)).toHaveLength(0);sqlite.exec('DROP TRIGGER fail_election');
    await act(async () => { expect(await mockStore.getState().dispatch({ type: 'advance' })).toBe(true); });
    const elected = mockStore.getState().world!, completed = elected.elections[0];
    expect(completed.status).toBe('completed');
    expect(elected.annual?.monthsProcessed).toBe(6);
    expect(completed.candidates[1].personId).toBe(race.candidates[1].personId);
    expect(completed.responseRoll).toBe(race.responseRoll);
    expect(elected.workHistory.find(item => item.id === completed.winningEmploymentId)!.grossEarned).toBe(0n);
    expect((await repository.load(initial.id)).elections).toEqual(elected.elections);
    expect((await repository.load(initial.id)).random).toEqual(elected.random);
    view.unmount();
    sqlite.close();
});
