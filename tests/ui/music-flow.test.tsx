import React from 'react';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react-native';
import { SafeAreaProvider } from 'react-native-safe-area-context';
import { createGameStore } from '../../src/state/gameStore';
import { decodeWorld, encodeWorld, World } from '../../src/game/model';
import { resolveCommand } from '../../src/game/engine';
import { endEmployment } from '../../src/game/systems/work';
import { careerPayQuote } from '../../src/game/systems/careers';
import { accountFor } from '../../src/game/systems/common';
import { recordingQuote } from '../../src/game/systems/music';
import { formatMoney } from '../../src/game/money';
import { SaveRepository } from '../../src/persistence/repository';
import { database } from '../support/sqlite';
import { ThemeProvider } from '../../src/ui/theme';
import fixture from '../fixtures/v3-employed-graduate.json';
let mockStore: ReturnType<typeof createGameStore>;
jest.mock('expo-router', () => ({ router: { back: jest.fn(), push: jest.fn() } }));
jest.mock('../../src/state/useGame', () => ({ useGame: (selector: unknown) => require('zustand').useStore(mockStore, selector) }));
import MusicStudio from '../../app/(game)/music-studio';
import { PendingEvent } from '../../src/ui/PendingEvent';
const frame = (content: React.ReactNode) => <SafeAreaProvider initialMetrics={{ frame: { x: 0, y: 0, width: 390, height: 844 }, insets: { top: 47, bottom: 34, left: 0, right: 0 } }}><ThemeProvider>{content}<PendingEvent /></ThemeProvider></SafeAreaProvider>;
function ack(world: World) { if (world.pending?.kind !== 'result')
    throw new Error('Expected actual result'); return resolveCommand(world, { type: 'acknowledge', resultId: world.pending.id }); }
test('a native recording failure rolls back the production start and saved response; retry preserves one recording and cold SQLite state', async () => {
    const { sqlite, driver } = database(), repository = new SaveRepository(driver);
    await repository.initialise();
    let initial = decodeWorld(JSON.stringify(fixture));
    endEmployment(initial);
    const person = initial.people[initial.activePersonId], cash = accountFor(initial);
    person.skills.music = 80;
    person.stats.health = 100;
    person.stats.energy = 100;
    initial.random.outcomes = 1;
    cash.cash += 100000000n;
    cash.openingCash += 100000000n;
    initial = ack(resolveCommand(initial, { type: 'select-career', kind: 'musician', quotedAnnualPay: careerPayQuote(initial, 'musician') }));
    initial = resolveCommand(initial, { type: 'advance' });
    expect(initial.pending?.id).toMatch(/^career_result_/);
    initial = ack(initial);
    expect(initial.annual?.pausedForPlanning).toBe(true);
    await repository.create(initial);
    mockStore = createGameStore({ repository: async () => repository, date: () => initial.date, id: () => 'life_unused' });
    await mockStore.getState().bootstrap();
    const view = render(frame(<MusicStudio />));
    expect(encodeWorld(mockStore.getState().world!)).toBe(encodeWorld(initial));
    expect(screen.getByRole('radio', { name: /^Single\./, checked: true })).toBeOnTheScreen();
    expect(screen.getByRole('radio', { name: /^Folk\./, checked: true })).toBeOnTheScreen();
    const quote = recordingQuote(initial, 'single');
    expect(screen.getByLabelText('Total production budget: ' + formatMoney({ minor: quote.cost, currency: quote.currency }))).toBeOnTheScreen();
    expect(screen.getByLabelText('First monthly payment: ' + formatMoney({ minor: quote.firstPayment, currency: quote.currency }))).toBeOnTheScreen();
    expect(screen.getByRole('button', { name: /Review Recording\. Give your recording a title/ })).toBeDisabled();
    fireEvent.changeText(screen.getByLabelText('Music release title'), 'Native Sessions');
    fireEvent.press(screen.getByRole('button', { name: 'Review Recording' }));
    sqlite.exec("CREATE TRIGGER fail_recording BEFORE INSERT ON receipts BEGIN SELECT RAISE(ABORT,'storage failure'); END");
    await act(async () => { fireEvent.press(screen.getByRole('button', { name: 'Start Recording' })); });
    await waitFor(() => expect(screen.getByText(/couldn't be saved/)).toBeOnTheScreen());
    expect(await repository.load(initial.id)).toEqual(initial);
    expect(mockStore.getState().world!.musicReleases).toEqual([]);
    sqlite.exec('DROP TRIGGER fail_recording');
    fireEvent.press(screen.getByRole('button', { name: 'Review Recording' }));
    await act(async () => { fireEvent.press(screen.getByRole('button', { name: 'Start Recording' })); });
    await waitFor(() => expect(screen.getByText('Studio time booked')).toBeOnTheScreen());
    const committed = mockStore.getState().world!;
    expect(committed.musicReleases).toHaveLength(1);
    expect(committed.musicReleases[0].title).toBe('Native Sessions');
    expect(committed.musicReleases[0].paidProduction).toBe(0n);
    expect(accountFor(committed).cash).toBe(accountFor(initial).cash);
    await act(async () => { fireEvent.press(screen.getByRole('button', { name: 'Continue' })); });
    const cold = await repository.load(initial.id);
    expect(cold.musicReleases).toEqual(committed.musicReleases);
    expect(cold.random).toEqual(committed.random);
    expect(cold.annual?.monthsProcessed).toBe(3);
    view.unmount();
    sqlite.close();
});
