import { createGameStore } from '../../src/state/gameStore';
import { SaveRepository } from '../../src/persistence/repository';
import { encodeWorld } from '../../src/game/model';
import { resolveCommand } from '../../src/game/engine';
import { activeSentence } from '../../src/game/systems/legalSchemas';
import { escapeContext } from '../../src/minigames/core/eligibility';
import { memorySolution } from '../support/escapeMemory';
import { escapePrisoner } from '../support/prisonEscape';
import { database } from '../support/sqlite';

test('SQLite escape starts and settlements roll back fully; cold reopening, exact retries and saved branches keep the same attempt', async () => {
  const { sqlite, driver } = database(), repository = new SaveRepository(driver);
  try {
    await repository.initialise();
    const initial = escapePrisoner();
    await repository.create(initial);
    const deps = { repository: async () => repository, date: () => initial.date, id: () => 'life_escape_branch' };
    let store = createGameStore(deps);
    expect(await store.getState().bootstrap()).toBe(true);
    const start = { type: 'mini-game-start' as const, kind: 'escape' as const, ownerId: activeSentence(initial)!.id, contextId: escapeContext(initial), assisted: true };
    const before = encodeWorld(store.getState().world!);
    sqlite.exec("CREATE TRIGGER fail_escape_start BEFORE INSERT ON receipts BEGIN SELECT RAISE(ABORT,'storage failure'); END");
    expect(await store.getState().dispatch(start)).toBe(false);
    expect(encodeWorld(store.getState().world!)).toBe(before);
    expect(encodeWorld(await repository.load(initial.id))).toBe(before);
    sqlite.exec('DROP TRIGGER fail_escape_start');
    expect(await store.getState().dispatch(start)).toBe(true);
    const session = store.getState().world!.miniGames.at(-1)!, solution = memorySolution(session);
    const first = { type: 'mini-game-input' as const, sessionId: session.id, index: 0, input: solution[0] };
    const reserved = encodeWorld(store.getState().world!);
    sqlite.exec("CREATE TRIGGER fail_escape_input BEFORE INSERT ON receipts BEGIN SELECT RAISE(ABORT,'storage failure'); END");
    expect(await store.getState().dispatch(first)).toBe(false);
    expect(encodeWorld(store.getState().world!)).toBe(reserved);
    sqlite.exec('DROP TRIGGER fail_escape_input');
    expect(await store.getState().dispatch(first)).toBe(true);
    expect(await store.getState().dispatch({ type: 'mini-game-pause', sessionId: session.id, elapsedMs: 100 })).toBe(true);
    const transcript = store.getState().world!.miniGames.at(-1)!;
    store = createGameStore(deps);
    expect(await store.getState().bootstrap()).toBe(true);
    expect(store.getState().world!.miniGames.at(-1)).toEqual(transcript);
    expect(await store.getState().dispatch({ type: 'mini-game-resume', sessionId: session.id })).toBe(true);
    for (let index = 1; index < solution.length; index++) expect(await store.getState().dispatch({ type: 'mini-game-input', sessionId: session.id, index, input: solution[index] })).toBe(true);
    const prepared = store.getState().world!, completion = { type: 'mini-game-complete' as const, sessionId: session.id }, expected = resolveCommand(prepared, completion), ready = encodeWorld(prepared);
    const [moment] = await repository.snapshot(initial.id, prepared.revision);
    const receipts = sqlite.prepare('SELECT count(*) AS count FROM receipts').get();
    sqlite.exec("CREATE TRIGGER fail_escape_result BEFORE INSERT ON receipts BEGIN SELECT RAISE(ABORT,'storage failure'); END");
    expect(await store.getState().dispatch(completion)).toBe(false);
    expect(encodeWorld(store.getState().world!)).toBe(ready);
    expect(encodeWorld(await repository.load(initial.id))).toBe(ready);
    expect(sqlite.prepare('SELECT count(*) AS count FROM receipts').get()).toEqual(receipts);
    sqlite.exec('DROP TRIGGER fail_escape_result');
    store = createGameStore(deps);
    expect(await store.getState().bootstrap()).toBe(true);
    expect(await store.getState().dispatch(completion)).toBe(true);
    expect(store.getState().world).toEqual(expected);
    expect(store.getState().world!.sentences.find(row => row.id === session.ownerId)?.state).toBe('escaped');
    const committed = encodeWorld(store.getState().world!);
    expect(await store.getState().dispatch(completion)).toBe(false);
    expect(encodeWorld(await repository.load(initial.id))).toBe(committed);
    const branch = await repository.restoreBranch(initial.id, moment.id, store.getState().world!.revision, 'life_escape_branch', 'escape-restore');
    expect(branch.miniGames.at(-1)).toMatchObject({ id: session.id, lifeId: branch.id, status: 'active', inputs: prepared.miniGames.at(-1)!.inputs });
    const branchStore = createGameStore(deps);
    expect(await branchStore.getState().bootstrap()).toBe(true);
    expect(await branchStore.getState().dispatch({ type: 'mini-game-forfeit', sessionId: session.id })).toBe(true);
    expect(branchStore.getState().world!.miniGames.at(-1)?.status).toBe('forfeited');
    expect(activeSentence(branchStore.getState().world!)?.id).toBe(session.ownerId);
    expect(encodeWorld(await repository.load(initial.id))).toBe(committed);
  } finally { sqlite.close(); }
});
