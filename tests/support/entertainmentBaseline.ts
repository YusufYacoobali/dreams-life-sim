/** Preserve historical cohorts by identity when new scenes join existing arrays. */
export function originalCatalogue(templates: readonly EventTemplate[], count = originalEventIds.length): EventTemplate[] {
  const byId = new Map(templates.map(template => [template.id, template]));
  return originalEventIds.slice(0, count).map(id => {
    const template = byId.get(id);
    if (!template) throw new Error('Missing original event: ' + id);
    return template;
  });
}
